"""Fill PRISMA checklist items deterministically and via LLM."""

from __future__ import annotations

import json
import logging
from typing import Any

from bastirr.prisma.checklist_items import ChecklistItem, get_prisma_checklist_items
from bastirr.prisma.context import PrismaContext
from bastirr.prisma.counts import PrismaCountsMetadata
from bastirr.prisma.render import FilledChecklistItem
from bastirr.prisma.search_strategy import (
    format_search_strategy_for_checklist,
    get_search_from_metadata,
)

logger = logging.getLogger(__name__)


def _format_quality(quality: Any) -> str:
    if not quality:
        return ""
    if isinstance(quality, str):
        return quality
    if isinstance(quality, list):
        parts: list[str] = []
        for item in quality:
            if isinstance(item, dict):
                idx = item.get("study_index", "?")
                rating = item.get("quality_rating", "N/A")
                parts.append(f"Study {idx}: {rating}")
            else:
                parts.append(str(item))
        return "; ".join(parts)
    return str(quality)


def _format_evidence_summary(evidence: list[Any]) -> str:
    if not evidence:
        return ""
    lines: list[str] = []
    for study in evidence[:10]:
        if not isinstance(study, dict):
            continue
        idx = study.get("study_index", "?")
        citation = study.get("citation", "")
        design = study.get("study_design", "")
        header = f"Study {idx}"
        if citation:
            header += f" ({citation})"
        lines.append(header)
        if design:
            lines.append(f"  - Design: {design}")
        pop = study.get("population", "")
        if pop:
            lines.append(f"  - Population: {str(pop)[:300]}")
        findings = study.get("key_findings", [])
        if isinstance(findings, list) and findings:
            lines.append(f"  - Key findings: {findings[0]}")
    return "\n".join(lines)


def _deterministic_response(
    item: ChecklistItem,
    ctx: PrismaContext,
    counts: PrismaCountsMetadata,
) -> tuple[str, str]:
    """Return (response, source) for deterministic/reference items."""
    search_metadata = ctx.search_metadata

    if item.id == "1":
        return "Systematic review report generated by Bastirr.", "pipeline"

    if item.id == "2":
        return (
            "See the PRISMA 2020 for Abstracts checklist (Table 2 in the PRISMA 2020 statement).",
            "prisma.abstract_checklist",
        )

    if item.id == "3":
        return ctx.background or "", "review.background"

    if item.id == "4":
        return ctx.objective or "", "review.objective"

    if item.id == "5":
        return ctx.selection_criteria or "", "review.selection_criteria"

    if item.id == "6":
        sources = search_metadata.get("information_sources")
        if sources:
            if isinstance(sources, list):
                return ", ".join(str(s) for s in sources), "search_metadata.information_sources"
            return str(sources), "search_metadata.information_sources"
        db_parts = [f"{name} (n={n})" for name, n in counts.databases.items()]
        return (
            "Cochrane benchmark dataset"
            + (f": {', '.join(db_parts)}" if db_parts else ""),
            "counts.databases",
        )

    if item.id == "7":
        sources = search_metadata.get("information_sources")
        n_candidates = search_metadata.get("num_candidates")
        search = get_search_from_metadata(search_metadata)

        if search.get("description") or search.get("boolean_query"):
            return (
                format_search_strategy_for_checklist(
                    search,
                    information_sources=sources,
                    num_candidates=n_candidates,
                ),
                "search_metadata.search_strategy",
            )
        return (
            "Candidate studies retrieved via Bastirr librarian from the pre-loaded "
            "Cochrane benchmark dataset (simulated search).",
            "default",
        )

    if item.id == "16a":
        db_summary = ", ".join(f"{k}: {v}" for k, v in counts.databases.items())
        return (
            f"Records identified: {sum(counts.databases.values())} "
            f"({db_summary}). Records screened: {counts.records_screened}. "
            f"Records excluded at title/abstract: {counts.records_excluded}. "
            f"Studies included: {counts.studies_included}. "
            "See flowchart.png for the PRISMA flow diagram.",
            "counts + flowchart.png",
        )

    if item.id == "16b":
        return (
            "See excluded_studies.md or excluded_studies.json for excluded records and reasons.",
            "excluded_studies.md",
        )

    if item.id == "17":
        text = _format_evidence_summary(ctx.evidence.get("evidence", []))
        return text or ctx.report_md[:2000], "evidence.json"

    if item.id == "18":
        qa = _format_quality(ctx.evidence.get("quality_assessment"))
        return qa, "evidence.quality_assessment"

    if item.id == "20b":
        synth = ctx.evidence.get("synthesis", "")
        return str(synth)[:3000] if synth else "", "evidence.synthesis"

    if item.id in ("20c", "20d"):
        return "", "not_applicable"

    if item.id == "22":
        strength = ctx.evidence.get("evidence_strength", "")
        limitations = ctx.evidence.get("limitations", [])
        parts: list[str] = []
        if strength:
            parts.append(f"Overall evidence strength: {strength}")
        if limitations:
            if isinstance(limitations, list):
                parts.extend(f"- {lim}" for lim in limitations)
            else:
                parts.append(str(limitations))
        return "\n".join(parts), "evidence.quality"

    if item.fill_mode == "manual":
        return "", "manual"

    return "", ""


def _parse_llm_json_response(text: str) -> dict[str, str]:
    """Parse checklist LLM output as JSON (optional markdown code fence only)."""
    text = text.strip()
    if text.startswith("```"):
        text = text.removeprefix("```json").removeprefix("```").strip()
        if text.endswith("```"):
            text = text[:-3].strip()
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        logger.warning("PRISMA LLM checklist fill returned invalid JSON")
        return {}
    if not isinstance(data, dict):
        return {}
    return {str(k): str(v) if v is not None else "" for k, v in data.items()}


def _llm_fill_items(
    items: list[ChecklistItem],
    ctx: PrismaContext,
    model: Any,
) -> dict[str, str]:
    """Single LLM call to fill narrative checklist items."""
    from smolagents.models import ChatMessage, MessageRole

    llm_items = [item for item in items if item.fill_mode == "llm"]
    if not llm_items or model is None:
        return {}

    item_specs = [
        {"id": item.id, "label": item.label, "description": item.description}
        for item in llm_items
    ]
    context_json = json.dumps(ctx.to_llm_dict(), ensure_ascii=False, indent=2)

    prompt = (
        "You are completing a PRISMA 2020 systematic review checklist for an "
        "automated Bastirr pipeline run.\n\n"
        "Rules:\n"
        "- Write 1-3 sentences per item, grounded ONLY in the provided context.\n"
        "- Describe what the Bastirr agents did (librarian search, gatekeeper screening, "
        "miner extraction, critic synthesis) where relevant.\n"
        "- If the context lacks information for an item, return an empty string.\n"
        "- Note that only title/abstract screening was performed (no full-text stage).\n"
        "- Return ONLY a JSON object mapping item id (string) to response (string).\n"
        "- Do not wrap the JSON in markdown code fences or add any other text.\n\n"
        f"Context:\n{context_json}\n\n"
        f"Items to fill:\n{json.dumps(item_specs, ensure_ascii=False, indent=2)}"
    )

    messages = [
        ChatMessage(
            role=MessageRole.USER,
            content=[{"type": "text", "text": prompt}],
        )
    ]

    try:
        response = model(messages)
        if isinstance(response.content, str):
            raw = response.content.strip()
        elif isinstance(response.content, list):
            raw = " ".join(
                item.get("text", "")
                for item in response.content
                if isinstance(item, dict)
            ).strip()
        else:
            raw = str(response.content).strip()
        return _parse_llm_json_response(raw)
    except Exception as exc:
        logger.warning("PRISMA LLM checklist fill failed: %s", exc)
        return {}


def fill_checklist(
    ctx: PrismaContext,
    counts: PrismaCountsMetadata,
    model: Any = None,
) -> list[FilledChecklistItem]:
    """Fill all checklist items and return structured results."""
    template = get_prisma_checklist_items()
    llm_responses = _llm_fill_items(template, ctx, model)

    filled: list[FilledChecklistItem] = []
    for item in template:
        structured: dict[str, Any] | None = None
        if item.fill_mode in ("deterministic", "reference"):
            response, source = _deterministic_response(item, ctx, counts)
            if item.id == "7":
                structured = get_search_from_metadata(ctx.search_metadata) or None
                if structured and not (structured.get("description") or structured.get("boolean_query")):
                    structured = None
        elif item.fill_mode == "llm":
            response = llm_responses.get(item.id, "")
            source = "llm" if response else "insufficient_context"
        else:
            response, source = "", "manual"

        filled.append(FilledChecklistItem(
            id=item.id,
            section=item.section,
            label=item.label,
            description=item.description,
            fill_mode=item.fill_mode,
            response=response,
            source=source,
            structured_response=structured,
        ))

    return filled
